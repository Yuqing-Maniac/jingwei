/* Register supplemental model/mission icons from reviewed country assets.
 * Run package_country.cjs first. Existing stable keys and generic assets stay intact. */
const fs=require('fs'),path=require('path'),sharp=require('sharp');
const root=path.resolve(__dirname,'../..'),dir=path.join(root,'assets/country-variants');
const definitions=JSON.parse(fs.readFileSync(path.join(dir,'supplemental.json')));
const catalog=JSON.parse(fs.readFileSync(path.join(dir,'catalog.json')));
// One generic concept may have team paints without claiming a national model.
async function genericPaints(entry){
 const input=path.join(dir,entry.genericMaster);let image=sharp(input);
 if(entry.genericRect)image=image.extract(entry.genericRect);
 const {data,info}=await image.ensureAlpha().raw().toBuffer({resolveWithObject:true});
 const w=info.width,h=info.height,seen=new Uint8Array(w*h);let largest=[];
 for(let q=0;q<w*h;q++){if(seen[q]||data[q*4+3]<40)continue;const part=[q];seen[q]=1;
  for(let k=0;k<part.length;k++){const p=part[k],x=p%w,y=Math.floor(p/w);for(const n of [x?p-1:-1,x<w-1?p+1:-1,y?p-w:-1,y<h-1?p+w:-1])if(n>=0&&!seen[n]&&data[n*4+3]>=40){seen[n]=1;part.push(n);}}
  if(part.length>largest.length)largest=part;
 }
 if(largest.length<w*h*.015)throw Error('Empty generic concept '+entry.key);
 const keep=new Uint8Array(w*h);for(const p of largest){const x=p%w,y=Math.floor(p/w);for(let dy=-2;dy<=2;dy++)for(let dx=-2;dx<=2;dx++)if(x+dx>=0&&x+dx<w&&y+dy>=0&&y+dy<h)keep[(y+dy)*w+x+dx]=1;}
 for(let q=0;q<w*h;q++)if(!keep[q])data[q*4+3]=0;
 const files={};for(const side of ['neutral','red','blue']){const pixels=Buffer.from(data);
  for(let q=0;q<pixels.length;q+=4){const r=pixels[q],g=pixels[q+1],b=pixels[q+2];if(b>r*1.24&&b>g*1.13&&b-r>25&&pixels[q+3]){
   if(side==='red'){pixels[q]=b;pixels[q+1]=Math.round(g*.72);pixels[q+2]=r;}
   if(side==='neutral'){const l=Math.round(r*.2126+g*.7152+b*.0722);pixels[q]=Math.round(l*.91);pixels[q+1]=Math.round(l*.97);pixels[q+2]=l;}
  }}
  files[side]='icons/'+entry.key+'-'+side+'.webp';
  await sharp(pixels,{raw:{width:w,height:h,channels:4}}).resize(232,232,{fit:'contain',background:{r:0,g:0,b:0,alpha:0}}).extend({top:12,bottom:12,left:12,right:12,background:{r:0,g:0,b:0,alpha:0}}).webp({quality:90,alphaQuality:100}).toFile(path.join(dir,files[side]));
 }
 return files;
}
(async()=>{const used=new Set(),icons=[];
for(const entry of definitions){
 if(used.has(entry.key))throw Error('Duplicate supplemental key '+entry.key);used.add(entry.key);
 const candidates=catalog.items.filter(x=>x.key===entry.key);
 if(!entry.countries.every(country=>candidates.some(x=>x.country===country)))throw Error('Missing country asset '+entry.key);
 const base=candidates.find(x=>x.country===(entry.originCountry||'cn'));
 const files=entry.genericMaster?await genericPaints(entry):base.files;
 const variants=Object.fromEntries(['neutral','red','blue'].map(side=>{
  const data=fs.readFileSync(path.join(dir,files[side]));
  return [side,'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256"><image width="256" height="256" href="data:image/webp;base64,'+data.toString('base64')+'"/></svg>'];
 }));
 const {countries,aliasOf,genericMaster,genericRect,sourceRecord,...metadata}=entry;
 icons.push({...metadata,variants,svg:variants.neutral});
}
fs.writeFileSync(path.join(root,'app/icons_recon.js'),'/* Generated by build/icons/package_recon.cjs. Public exterior artwork. */\nICON_LIB.push(...'+JSON.stringify(icons)+');\n');
console.log('Supplemental icons:',icons.length);
})().catch(error=>{console.error(error);process.exit(1)});
